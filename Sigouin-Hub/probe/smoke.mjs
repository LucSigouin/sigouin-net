import { chromium } from '@playwright/test';
const OUT = new URL('./shots/smoke', import.meta.url).pathname;
const t0 = Date.now(); const sec = () => ((Date.now() - t0) / 1000).toFixed(1) + 's';
const browser = await chromium.launch({ args: ['--use-angle=metal', '--enable-gpu', '--ignore-gpu-blocklist'] });
const page = await browser.newPage({ viewport: { width: 1440, height: 900 } });
const errors = []; page.on('pageerror', e => errors.push(e.message)); page.on('console', m => { if (m.type() === 'error') errors.push(m.text()); });
await page.goto('https://sigouin.net/hub/');
await page.waitForFunction(() => window.__hub?.state?.() === 'play', null, { timeout: 120000 });
console.log('play at', sec(), 'tier', await page.evaluate(() => window.__hub.tier()), 'level', await page.evaluate(() => window.__hub.level()));
await page.evaluate(() => window.__hub.pauseDay(0.35));
const fps = () => page.evaluate(() => new Promise(r => { let n = 0; const s = performance.now(); const f = () => { n++; performance.now() - s < 3000 ? requestAnimationFrame(f) : r(n / 3); }; requestAnimationFrame(f); }));
console.log('fps', (await fps()).toFixed(1), 'gpu', await page.evaluate(() => { const g = document.createElement('canvas').getContext('webgl2'); const e = g.getExtension('WEBGL_debug_renderer_info'); return g.getParameter(e.UNMASKED_RENDERER_WEBGL); }));
await page.screenshot({ path: OUT + '/1-spawn.png' });
const items = await page.evaluate(() => window.__hub.interactables());
console.log('interactables', items.map(i => i.id).join(', '));
await page.keyboard.down('KeyW'); await page.waitForTimeout(1500); await page.keyboard.up('KeyW'); await page.waitForTimeout(500);
await page.screenshot({ path: OUT + '/2-walked.png' });
await page.evaluate(() => window.__hub.view([0, 40, 45], [0, 0, -5]));
await page.waitForTimeout(800); await page.screenshot({ path: OUT + '/3-aerial.png' });
console.log('errors', errors.length ? errors.slice(0, 5) : 'none', 'done at', sec());
await browser.close();
